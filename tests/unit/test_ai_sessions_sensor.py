# --- Hermes: state.db messages ------------------------------------------------

def _hermes_db(tmp_path, rows):
    p = tmp_path / "state.db"
    con = sqlite3.connect(p)
    con.execute("CREATE TABLE sessions (id TEXT PRIMARY KEY, title TEXT, model TEXT, "
                "source TEXT, cwd TEXT, git_branch TEXT)")
    con.execute("CREATE TABLE messages (id INTEGER PRIMARY KEY AUTOINCREMENT, "
                "session_id TEXT, role TEXT, content TEXT, timestamp REAL)")
    con.execute("INSERT INTO sessions VALUES (?,?,?,?,?,?)",
                ("sess-1", "Fix the login bug", "claude-opus-4-7", "api_server", None, None))
    for role, content, ts in rows:
        con.execute("INSERT INTO messages (session_id, role, content, timestamp) VALUES (?,?,?,?)",
                    ("sess-1", role, content, ts))
    con.commit()
    con.close()
    return p


@pytest.mark.asyncio
async def test_hermes_db_forward_only_and_cursor(tmp_path):
    now = time.time()
    db = _hermes_db(tmp_path, [
        ("user", "You are bot, an AI agent employee ...", now - 50),  # noise
        ("assistant", "Looking into the login handler now.", now - 40),
        ("tool", "some stdout", now - 35),                            # role filtered by SQL
        ("assistant", "", now - 30),                                  # empty skipped
        ("assistant", "Nothing to do.", now - 20),                    # heartbeat noise
    ])
    s = _sensor()
    s._hermes_cursor = None
    await s._poll_hermes_db(db, first_pass=True,
                            backfill_cutoff=now - 3600, backfill_max_lines=999)
    evs = await _drain(s)
    assert len(evs) == 1
    e = evs[0]
    assert e.app == "hermes"
    assert e.payload["role"] == "assistant"
    assert e.payload["text"] == "Looking into the login handler now."
    assert e.payload["model"] == "claude-opus-4-7"
    assert e.payload["project"] == "Fix the login bug"
    assert e.window_title == "hermes: Fix the login bug"

    # second poll: nothing new
    await s._poll_hermes_db(db, first_pass=False,
                            backfill_cutoff=now - 3600, backfill_max_lines=999)
    assert await _drain(s) == []

    # a new row arrives → picked up
    con = sqlite3.connect(db)
    con.execute("INSERT INTO messages (session_id, role, content, timestamp) VALUES (?,?,?,?)",
                ("sess-1", "assistant", "Pushed the fix.", time.time()))
    con.commit()
    con.close()
    await s._poll_hermes_db(db, first_pass=False,
                            backfill_cutoff=now - 3600, backfill_max_lines=999)
    evs = await _drain(s)
    assert [e.payload["text"] for e in evs] == ["Pushed the fix."]


